private func make(_ w: Int, _ h: Int, _ f: (Int, Int) -> (Int, Int, Int)) -> RGBImage {
    var p = [UInt8]()
    for y in 0..<h { for x in 0..<w { let c = f(x, y); p += [UInt8(c.0 & 255), UInt8(c.1 & 255), UInt8(c.2 & 255)] } }
    return RGBImage(width: w, height: h, pixels: p)
}

