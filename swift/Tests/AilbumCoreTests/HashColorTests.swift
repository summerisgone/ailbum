@Test func testPhashParity() {
    let img = make(32, 32) { x, y in (x * 8, y * 8, (x + y) * 4) }
    let bits = HashColor.features(img).phash.map { $0 ? "1" : "0" }.joined()
    #expect(bits == "1000000000100000000101010000000001010000000010000101010000001010")
}

@Test func testHistogramParity() {
    let img = make(256, 256) { x, y in (x, y, 255 - x) }
    let h = HashColor.features(img).histogram
    #expect(h.count == 384)
    for i in 0..<384 { #expect(abs(h[i] - goldenHistogram[i]) < 1e-4, "bin \(i)") }
}

@Test func testHistogramUnitNorm() {
    let img = make(256, 256) { x, y in (x, y, 255 - x) }
    let h = HashColor.features(img).histogram
    let norm = h.reduce(0) { $0 + $1 * $1 }.squareRoot()
    #expect(abs(norm - 1) < 1e-5)
}

@Test func testBlackImageHistogram() {
    let img = RGBImage(width: 256, height: 256, pixels: [UInt8](repeating: 0, count: 256 * 256 * 3))
    let h = HashColor.features(img).histogram
    #expect(h[0] == 1.0)
    #expect(h.dropFirst().allSatisfy { $0 == 0 })
}

@Test func testLengths() {
    let img = RGBImage(width: 32, height: 32, pixels: [UInt8](repeating: 7, count: 32 * 32 * 3))
    let f = HashColor.features(img)
    #expect(f.phash.count == 64)
    #expect(f.histogram.count == 384)
}

@Test func testHammingSimilarity() {
    #expect(HashColor.hamming([true, false, true], [true, true, false]) == 2)
    #expect(abs(HashColor.similarity([0.6, 0.8], [0.6, 0.8]) - 1) < 1e-6)
}

@Test func testPhashNoisyParity() {
    var v: UInt64 = 1
    var px = [UInt8]()
    for _ in 0..<(32 * 32 * 3) {
        v = (v * 1103515245 + 12345) & 0x7fffffff
        px.append(UInt8((v >> 16) & 255))
    }
    let bits = HashColor.features(RGBImage(width: 32, height: 32, pixels: px)).phash.map { $0 ? "1" : "0" }.joined()
    #expect(bits == "1011110100110101001010100000110010111010001001011110011101100100")
}
