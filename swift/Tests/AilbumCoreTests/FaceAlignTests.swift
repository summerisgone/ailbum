@Suite struct FaceAlignTests {
    @Test func testTemplateIdentity() {
        let image = gradient(112, 112)
        let out = FaceAlign.alignCrop(image, landmarks: template)
        #expect(out.width == 112 && out.height == 112)
        var maxDiff = 0
        for i in 0..<image.pixels.count { maxDiff = max(maxDiff, abs(Int(out.pixels[i]) - Int(image.pixels[i]))) }
        #expect(maxDiff <= 1)
    }

    @Test func testParityWarp() {
        let landmarks = template.map { $0 * 1.5 + SIMD2<Float>(10, 5) }
        let out = FaceAlign.alignCrop(gradient(200, 160), landmarks: landmarks)
        var maxDiff = 0
        var k = 0
        for y in stride(from: 3, to: 112, by: 9) {
            for x in stride(from: 3, to: 112, by: 9) {
                for c in 0..<3 {
                    maxDiff = max(maxDiff, abs(Int(out.pixels[(y * 112 + x) * 3 + c]) - golden[k]))
                    k += 1
                }
            }
        }
        #expect(k == golden.count)
        #expect(maxDiff <= 1)
    }

    @Test(.enabled(if: ModelStore.available("sface")))
    func testEmbedNormalised() throws {
        let e = try FaceAlign.embed(gradient(112, 112))
        #expect(e.count == 128)
        let norm = e.reduce(0) { $0 + Double($1) * Double($1) }.squareRoot()
        #expect(abs(norm - 1) < 1e-4)
    }
}
