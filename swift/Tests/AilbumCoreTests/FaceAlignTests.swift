private func gradient(_ w: Int, _ h: Int) -> RGBImage {
    var p = [UInt8]()
    for y in 0..<h { for x in 0..<w { p += [UInt8((x * 5 + y) % 256), UInt8((x + y * 3) % 256), UInt8((x * 2 + y * 2) % 256)] } }
    return RGBImage(width: w, height: h, pixels: p)
}

